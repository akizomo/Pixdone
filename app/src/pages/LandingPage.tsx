/* ── Mobile auto-play helpers ─────────────────────────────────────── */

/**
 * Returns true on touch-primary devices (no fine pointer). Used to decide
 * whether a card should auto-activate on scroll-into-view instead of
 * relying on hover.
 */
function useCoarsePointer(): boolean {
  const subscribe = (cb: () => void) => {
    if (typeof window === 'undefined') return () => {};
    const mq = window.matchMedia('(pointer: coarse)');
    mq.addEventListener?.('change', cb);
    return () => mq.removeEventListener?.('change', cb);
  };
  return useSyncExternalStore(
    subscribe,
    () => typeof window !== 'undefined' && window.matchMedia('(pointer: coarse)').matches,
    () => false,
  );
}

/**
 * Returns true while the element is intersecting the viewport by at least
 * `threshold`. Used to auto-activate feature cards on mobile during scroll.
 */
function useInView(ref: React.RefObject<HTMLElement | null>, threshold = 0.5): boolean {
  const [inView, setInView] = useState(false);
  useEffect(() => {
    const el = ref.current;
    if (!el || typeof IntersectionObserver === 'undefined') return;
    const obs = new IntersectionObserver(
      ([entry]) => setInView(entry.isIntersecting && entry.intersectionRatio >= threshold),
      { threshold },
    );
    obs.observe(el);
    return () => obs.disconnect();
  }, [ref, threshold]);
  return inView;
}

