/**
 * Stay Focused feature card — hover-driven Pomodoro demo.
 * On mouse enter: plays the app's existing retro chiptune via startBgm('retro')
 * and counts down a mini CRT-style timer display from 25:00.
 * On mouse leave: stops BGM and resets.
 * At 0:00: plays the pomodoro-complete fanfare and stops.
 */
const LP_BGM_TRACKS: BgmTrack[] = ['retro', 'synthwave', 'chill', 'nightCity', 'rain', 'fireplace'];

function StayFocusedCard({ isJa }: { isJa: boolean }) {
  const TOTAL = 25 * 60;
  // Mobile auto-play runs for a short teaser only so BGM doesn't linger
  // while the user scrolls past or reads the rest of the page.
  const MOBILE_AUTOPLAY_MS = 6000;

  const cardRef = useRef<HTMLElement>(null);
  const isCoarse = useCoarsePointer();
  const inView = useInView(cardRef);
  const [seconds, setSeconds] = useState(TOTAL);
  const [hovering, setHovering] = useState(false);
  const [mobileAutoActive, setMobileAutoActive] = useState(false);
  const bgmStartedRef = useRef(false);
  const bgmIdxRef = useRef(0);

  // Mobile: run a capped teaser when the card scrolls into view.
  useEffect(() => {
    if (!isCoarse) return;
    if (!inView) {
      setMobileAutoActive(false);
      return;
    }
    setMobileAutoActive(true);
    const stopId = window.setTimeout(() => setMobileAutoActive(false), MOBILE_AUTOPLAY_MS);
    return () => window.clearTimeout(stopId);
  }, [isCoarse, inView]);

  const isActive = hovering || mobileAutoActive;

  useEffect(() => {
    if (!isActive) {
      if (bgmStartedRef.current) {
        stopBgm();
        bgmStartedRef.current = false;
      }
      setSeconds(TOTAL);
      return;
    }
    if (isBgmOn()) {
      const track = LP_BGM_TRACKS[bgmIdxRef.current % LP_BGM_TRACKS.length];
      bgmIdxRef.current = (bgmIdxRef.current + 1) % LP_BGM_TRACKS.length;
      startBgm(track);
      bgmStartedRef.current = true;
    }
    const id = window.setInterval(() => {
      setSeconds((s) => Math.max(0, s - 1));
    }, 1000);
    return () => window.clearInterval(id);
  }, [isActive]);

  useEffect(() => {
    if (isActive && seconds === 0) {
      playSound('focusPomodoroComplete');
      setHovering(false);
      setMobileAutoActive(false);
    }
  }, [seconds, isActive]);

  // Unmount safety — never leak BGM beyond the LP card lifetime.
  useEffect(() => () => {
    if (bgmStartedRef.current) {
      stopBgm();
      bgmStartedRef.current = false;
    }
  }, []);

  const mm = String(Math.floor(seconds / 60)).padStart(2, '0');
  const ss = String(seconds % 60).padStart(2, '0');

  return (
    <article
      ref={cardRef}
      className={`lp-feature-card lp-feature-card--interactive${isActive ? ' is-active' : ''}`}
      onMouseEnter={() => setHovering(true)}
      onMouseLeave={() => setHovering(false)}
    >
      <span className="lp-feature-card__num">02</span>
      <h3 className="lp-feature-card__title">
        {isJa ? '楽しく、捗る。' : 'Stay Focused'}
      </h3>
      <ul className="lp-feature-card__list">
        <li>{isJa ? 'ポモドーロ・タイマー内蔵' : 'Built-in Pomodoro timer'}</li>
        <li>{isJa ? 'シンプルなタスクリスト — 余計な機能なし' : 'Simple task lists — no clutter, no complexity'}</li>
        <li>{isJa ? '毎日・毎週の習慣づくりに繰り返しタスク' : 'Repeat tasks for daily and weekly habits'}</li>
      </ul>
      <div className="lp-focus-demo">
        <div className="lp-focus-demo__digits">{mm}:{ss}</div>
        <PacmanProgress
          remaining={seconds}
          totalSeconds={TOTAL}
          timerState={hovering ? 'running' : 'idle'}
        />
      </div>
    </article>
  );
}

