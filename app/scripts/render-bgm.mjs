/**
 * Renders the focus BGM tracks (src/services/bgm.ts) to seamless loop files for the native
 * iOS app, which cannot keep Web Audio running in the background.
 *
 * Output:
 *   public/bgm/{track}.caf                — mono AAC loops (CAF keeps the encoder delay info,
 *                                           so the loop is gapless when decoded)
 *   src/services/bgmNativeTracks.ts        — per-track gain that restores the live mix level
 *
 * Prerequisites: Chromium for Playwright (`npx playwright install chromium`), macOS `afconvert`.
 * Usage: node scripts/render-bgm.mjs   (re-run after changing a track in bgm.ts)
 */
import { build } from 'esbuild';
import { chromium } from 'playwright';
import { execFileSync } from 'node:child_process';
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = path.join(ROOT, 'public/bgm');
const MANIFEST = path.join(ROOT, 'src/services/bgmNativeTracks.ts');
// Fireplace is no longer selectable (getBgmTrack migrates it to retro).
const TRACKS = ['retro', 'synthwave', 'chill', 'rain', 'nightCity'];
const SAMPLE_RATE = 44100;
const PEAK = 0.89;

function wav16(samples) {
  const buf = Buffer.alloc(44 + samples.length * 2);
  buf.write('RIFF', 0); buf.writeUInt32LE(36 + samples.length * 2, 4); buf.write('WAVE', 8);
  buf.write('fmt ', 12); buf.writeUInt32LE(16, 16); buf.writeUInt16LE(1, 20); buf.writeUInt16LE(1, 22);
  buf.writeUInt32LE(SAMPLE_RATE, 24); buf.writeUInt32LE(SAMPLE_RATE * 2, 28);
  buf.writeUInt16LE(2, 32); buf.writeUInt16LE(16, 34);
  buf.write('data', 36); buf.writeUInt32LE(samples.length * 2, 40);
  for (let i = 0; i < samples.length; i++) {
    buf.writeInt16LE(Math.round(Math.max(-1, Math.min(1, samples[i])) * 32767), 44 + i * 2);
  }
  return buf;
}

const bundle = await build({
  entryPoints: [path.join(ROOT, 'src/services/bgm.ts')],
  bundle: true, write: false, format: 'iife', globalName: 'PixBgm', target: 'es2020',
});

const browser = await chromium.launch();
const tmp = await mkdtemp(path.join(tmpdir(), 'pixdone-bgm-'));
const gains = {};
try {
  const page = await browser.newPage();
  await page.setContent('<!doctype html><html><body></body></html>');
  await page.addScriptTag({ content: bundle.outputFiles[0].text });
  await mkdir(OUT_DIR, { recursive: true });

  for (const track of TRACKS) {
    const base64 = await page.evaluate(async ([t, sr]) => {
      const loop = await window.PixBgm.renderBgmLoop(t, sr);
      const bytes = new Uint8Array(loop.buffer);
      let bin = '';
      for (let i = 0; i < bytes.length; i += 0x8000) bin += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
      return btoa(bin);
    }, [track, SAMPLE_RATE]);
    const raw = Buffer.from(base64, 'base64');
    const samples = new Float32Array(raw.buffer, raw.byteOffset, raw.byteLength / 4);

    let peak = 0;
    for (const v of samples) peak = Math.max(peak, Math.abs(v));
    const scale = PEAK / peak;
    for (let i = 0; i < samples.length; i++) samples[i] *= scale;
    gains[track] = 1 / scale;

    const wavPath = path.join(tmp, `${track}.wav`);
    const cafPath = path.join(OUT_DIR, `${track}.caf`);
    await writeFile(wavPath, wav16(samples));
    execFileSync('afconvert', ['-f', 'caff', '-d', 'aac', '-b', '96000', wavPath, cafPath]);
    console.log(`${track}: ${(samples.length / SAMPLE_RATE).toFixed(2)}s, gain ${gains[track].toFixed(4)} → ${path.relative(ROOT, cafPath)}`);
  }
} finally {
  await browser.close();
  await rm(tmp, { recursive: true, force: true });
}

const lines = TRACKS.map((t) => `  ${t}: ${gains[t].toFixed(6)},`).join('\n');
await writeFile(MANIFEST, `// Generated by scripts/render-bgm.mjs — do not edit.
import type { BgmTrack } from './bgm';

/**
 * public/bgm/{track}.caf files are peak-normalized; multiply the BGM volume by this gain
 * to play them at the same level as the live Web Audio mix.
 */
export const NATIVE_BGM_GAIN: Partial<Record<BgmTrack, number>> = {
${lines}
};
`);
console.log(`wrote ${path.relative(ROOT, MANIFEST)}`);
